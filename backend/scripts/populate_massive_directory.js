async function run() {
  console.log('1. Loading sent history...');
  const sentLog = JSON.parse(fs.readFileSync(path.join(__dirname, '../data/sent_log.json'), 'utf8') || '[]');
  const contactedDomains = new Set();
  sentLog.forEach(x => {
    if (x.email) {
      const p = x.email.split('@')[1];
      if (p) contactedDomains.add(p.toLowerCase().trim());
    }
  });
  console.log(`Already contacted domains in sent_log: ${contactedDomains.size}`);

  console.log(`\n2. Filtering ${candidates.length} candidate companies for uniqueness and uncontacted status...`);
  const uniqueCandidates = [];
  const seen = new Set();

  for (const c of candidates) {
    const d = (c.domain || '').toLowerCase().trim();
    if (!d || seen.has(d)) continue;
    seen.add(d);

    if (contactedDomains.has(d)) {
      // Already sent in past
      continue;
    }

    uniqueCandidates.push({
      company: c.company,
      domain: d,
      type: c.type || 'Remote'
    });
  }

  console.log(`Uncontacted unique candidates to check MX: ${uniqueCandidates.length}`);

  console.log('\n3. Performing concurrent DNS MX checks...');
  const verified = [];
  const CONCURRENCY = 25;

  for (let i = 0; i < uniqueCandidates.length; i += CONCURRENCY) {
    const chunk = uniqueCandidates.slice(i, i + CONCURRENCY);
    await Promise.all(chunk.map(async (c) => {
      try {
        const mx = await dns.resolveMx(c.domain);
        if (mx && mx.length > 0) {
          verified.push(c);
        }
      } catch (e) {
        // failed MX
      }
    }));
    process.stdout.write(`\rProgress: ${Math.min(i + CONCURRENCY, uniqueCandidates.length)} / ${uniqueCandidates.length} checked | Active MX verified: ${verified.length}`);
  }

  console.log(`\n\nTotal fresh MX-verified companies: ${verified.length}`);

  // Write verified pool to json file
  fs.writeFileSync(path.join(__dirname, 'verified_massive_pool.json'), JSON.stringify(verified, null, 2), 'utf8');

  return verified;
}

run().catch(console.error);
